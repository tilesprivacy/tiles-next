"use client"

import { useCallback, useEffect, useMemo, useRef, useState } from "react"
import Link from "next/link"
import { usePathname, useRouter } from "next/navigation"
import ReactMarkdown from "react-markdown"

interface PagefindSubResult {
  url: string
  title: string
  excerpt: string
}

interface PagefindResultData {
  url: string
  excerpt: string
  meta?: { title?: string }
  sub_results?: PagefindSubResult[]
}

interface PagefindResult {
  id: string
  data: () => Promise<PagefindResultData>
}

interface Pagefind {
  options: (options: Record<string, unknown>) => Promise<void>
  debouncedSearch: (
    query: string,
  ) => Promise<{ results: PagefindResult[] } | null>
}

interface SearchHit {
  id: string
  url: string
  title: string
  excerpt: string
}

let pagefindPromise: Promise<Pagefind | null> | null = null

async function loadPagefind(): Promise<Pagefind | null> {
  pagefindPromise ??= (async () => {
    try {
      const pagefind: Pagefind = await import(
        /* webpackIgnore: true */
        /* turbopackIgnore: true */
        // @ts-expect-error -- runtime asset generated by the pagefind build step
        "/_pagefind/pagefind.js"
      )
      await pagefind.options({ baseUrl: "/" })
      return pagefind
    } catch {
      // Index is only generated by `npm run build`; fall back to AI-only search.
      return null
    }
  })()
  return pagefindPromise
}

/** Pagefind indexes prerendered HTML under `.next`, so raw result URLs look
 * like `/server/app/book.html`; map them back to live routes. */
function normalizePagefindUrl(rawUrl: string): string {
  const url = rawUrl
    .replace(/^\/server\/app/, "")
    .replace(/\.html(#|$)/, "$1")
    .replace(/\/index(#|$)/, "/$1")
  return url.startsWith("/") ? url : `/${url}`
}

/** The anchored section of the page that matches the query hardest, so a
 * click can land on that section instead of the top of the page. */
function pickAnchoredSubResult(
  item: PagefindResultData,
): PagefindSubResult | null {
  const countMarks = (excerpt: string) => excerpt.split("<mark>").length - 1
  let best: PagefindSubResult | null = null
  for (const sub of item.sub_results ?? []) {
    if (!sub.url.includes("#")) continue
    if (!best || countMarks(sub.excerpt) > countMarks(best.excerpt)) best = sub
  }
  return best
}

